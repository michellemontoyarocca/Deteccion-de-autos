# Definir la ruta de la carpeta en Google Drive
dataset_path = "/content/drive/MyDrive/Fundamentos CNN"

datagen = ImageDataGenerator(
    rescale=1./255,
    rotation_range=20,
    zoom_range=0.2,
    width_shift_range=0.1,
    height_shift_range=0.1,
    horizontal_flip=True,
    brightness_range=(0.7, 1.3),
    validation_split=0.2
)

train_generator = datagen.flow_from_directory(
    dataset_path,
    target_size=(224, 224),
    batch_size=32,
    class_mode="binary",
    subset="training"
)
validation_generator = datagen.flow_from_directory(
    dataset_path,
    target_size=(224, 224),
    batch_size=32,
    class_mode="binary",
    subset="validation"
)

y_true = train_generator.classes
classes = np.unique(y_true)
weights = compute_class_weight(class_weight="balanced", classes=classes, y=y_true)
class_weights = dict(zip(classes, weights))
print("Class weights:", class_weights)

"""TRANSFER LEARNING: MOBILENETV2 + CABEZA CUSTOM"""

# se carga el modelo entrenado previamente con la funcion relu
base = MobileNetV2(
    weights="imagenet",
    include_top=False,
    input_shape=(224, 224, 3)
)
for layer in base.layers:
    layer.trainable = False

x = GlobalAveragePooling2D()(base.output)
x = Dense(256, activation="relu")(x)
x = Dropout(0.5)(x)
output = Dense(1, activation="sigmoid")(x)

tl_model = Model(inputs=base.input, outputs=output)
tl_model.compile(
    optimizer=Adam(learning_rate=1e-4),
    loss="binary_crossentropy",
    metrics=["accuracy"]
)
tl_model.summary()

callbacks = [
    ReduceLROnPlateau(monitor="val_loss", factor=0.5, patience=3, verbose=1)
]
history = tl_model.fit(
    train_generator,
    validation_data=validation_generator,
    epochs=20,
    class_weight=class_weights,
    callbacks=callbacks,
    verbose=1
)


# Mostrar curvas
plt.figure(figsize=(12,4))
plt.subplot(1,2,1)
plt.plot(history.history["loss"], label="train loss")
plt.plot(history.history["val_loss"], label="val loss")
plt.legend(), plt.title("Loss")
plt.subplot(1,2,2)
plt.plot(history.history["accuracy"], label="train acc")
plt.plot(history.history["val_accuracy"], label="val acc")
plt.legend(), plt.title("Accuracy")
plt.show()

tl_model.save("emergency_vehicle_detector_tl.keras")
print("Modelo guardado como emergency_vehicle_detector_tl.keras")

def predict_emergency_vehicle(image_path, model, threshold=0.5):
    img = cv2.imread(image_path)
    img_resized = cv2.resize(img, (224, 224))
    img_exp = np.expand_dims(img_resized / 255.0, axis=0)

    score = float(model.predict(img_exp)[0][0])
    print(f"Raw prediction score: {score:.3f}")

    if score > threshold:
        label, color = " No emergency vehicle detected", (0, 255, 0)
    else:
        label, color = " Emergency vehicle detected", (0, 0, 255)

    cv2.putText(img, label, (10, 30),
                cv2.FONT_HERSHEY_SIMPLEX, 1, color, 2, cv2.LINE_AA)
    cv2_imshow(img)

