from sklearn.metrics import roc_curve, auc, classification_report, confusion_matrix

# 1) Carga los dos modelos
model_relu  = load_model("emergency_vehicle_detector_tl.keras")
model_swish = load_model("emergency_vehicle_detector_swish.keras")

# 2) Evalúa loss & accuracy directo en el generator
loss_r, acc_r = model_relu.evaluate(validation_generator, verbose=0)
loss_s, acc_s = model_swish.evaluate(validation_generator, verbose=0)
print(f"ReLU  model → loss: {loss_r:.3f}, acc: {acc_r:.3f}")
print(f"Swish model → loss: {loss_s:.3f}, acc: {acc_s:.3f}")

# 3) Recolecta todas las etiquetas y scores
y_true = []
scores_r, scores_s = [], []
for Xb, yb in validation_generator:
    y_true.extend(yb)
    scores_r.extend(model_relu .predict(Xb).ravel())
    scores_s.extend(model_swish.predict(Xb).ravel())
    if len(y_true) >= validation_generator.samples:
        break
y_true = np.array(y_true)

# 4) ROC & AUC
fpr_r, tpr_r, _ = roc_curve(y_true, scores_r)
fpr_s, tpr_s, _ = roc_curve(y_true, scores_s)
auc_r = auc(fpr_r, tpr_r)
auc_s = auc(fpr_s, tpr_s)

plt.figure(figsize=(6,6))
plt.plot(fpr_r, tpr_r, label=f"ReLU  (AUC={auc_r:.3f})")
plt.plot(fpr_s, tpr_s, label=f"Swish (AUC={auc_s:.3f})")
plt.plot([0,1],[0,1],"--", color="gray")
plt.xlabel("False Positive Rate")
plt.ylabel("True Positive Rate")
plt.title("ROC Curve Comparison")
plt.legend()
plt.show()

# 5) Classification report a umbral=0.5
y_pred_r = (np.array(scores_r) > 0.5).astype(int)
y_pred_s = (np.array(scores_s) > 0.5).astype(int)

print("=== Classification Report ReLU ===")
print(classification_report(y_true, y_pred_r))
print("Confusion Matrix ReLU:")
print(confusion_matrix(y_true, y_pred_r))

print("\n=== Classification Report Swish ===")
print(classification_report(y_true, y_pred_s))
